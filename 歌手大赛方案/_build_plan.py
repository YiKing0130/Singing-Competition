def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hexcolor)
    tcPr.append(shd)


def table(rows, widths, fs=10, header=True, center_cols=(), bold_rows=(), red_rows=()):
    nr, nc = len(rows), len(rows[0])
    t = doc.add_table(rows=nr, cols=nc)
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    tblPr = t._tbl.tblPr
    layout = OxmlElement('w:tblLayout')
    layout.set(qn('w:type'), 'fixed')
    tblPr.append(layout)
    for gc, wcm in zip(t._tbl.tblGrid.findall(qn('w:gridCol')), widths):
        gc.set(qn('w:w'), str(int(wcm * 567)))
    for ri, row in enumerate(rows):
        for ci in range(nc):
            cell = t.cell(ri, ci)
            cell.width = Cm(widths[ci])
            cell.text = ''
            p = cell.paragraphs[0]
            p.paragraph_format.line_spacing = 1.18
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
            if ci in center_cols:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(row[ci] if ci < len(row) else '')
            _font(r, size=fs, bold=(ri == 0 and header) or (ri in bold_rows))
            if ri == 0 and header:
                r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
                shade(cell, '1F3864')
            elif ri in red_rows:
                shade(cell, 'FBEEEE')
            elif ri % 2 == 0:
                shade(cell, 'F3F6FA')
    return t


